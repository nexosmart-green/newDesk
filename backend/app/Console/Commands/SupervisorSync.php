<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Symfony\Component\Process\Process;

/**
 * Single source of truth for background processes (RNF-11): never crontab.
 * Writes one supervisord program per entry and reloads supervisor.
 */
class SupervisorSync extends Command
{
    protected $signature = 'supervisor:sync
        {--dir= : Where to write the .conf (default: SUPERVISOR_CONF_DIR)}
        {--dry-run : Print the config instead of writing it}
        {--no-reload : Do not call supervisorctl}';

    protected $description = 'Generate the Supervisord config for queue, scheduler, Reverb and monitoring, and reload';

    /**
     * Add new background processes here (e.g. lock ingestion in R2).
     *
     * @return array<string, array{command: string, numprocs?: int, stopwaitsecs?: int}>
     */
    public static function programs(): array
    {
        return [
            // Mail is throttled to 1/s inside the job middleware, not by worker count.
            'queue' => ['command' => 'queue:work redis --queue=default,mail --sleep=1 --tries=3 --max-time=3600', 'numprocs' => 2, 'stopwaitsecs' => 3600],
            // Runs the minute-level jobs: timer cuts (RF-05.06), forgotten timers, alerts.
            'scheduler' => ['command' => 'schedule:work'],
            'reverb' => ['command' => 'reverb:start --host=0.0.0.0 --port='.config('newdesk.supervisor.reverb_port')],
            // RF-13.02. One process polls every agent; it restarts itself every hour. On stop it lets
            // running agent calls (60 s at most) finish.
            'monitoring-poller' => ['command' => 'monitoring:poll', 'stopwaitsecs' => 75],
            'monitoring-worker' => ['command' => 'queue:work redis --queue=monitoring --sleep=1 --tries=3 --max-time=3600', 'numprocs' => 2, 'stopwaitsecs' => 120],
            // RF-13.09: one process, so Discord messages go out one at a time and in order; server-wide
            // notices first (D-107).
            'monitoring-discord' => ['command' => 'queue:work redis --queue=discord-priority,discord --sleep=1 --max-time=3600', 'stopwaitsecs' => 60],
        ];
    }

    public function handle(): int
    {
        $config = $this->render();

        if ($this->option('dry-run')) {
            $this->line($config);

            return self::SUCCESS;
        }

        $directory = $this->option('dir') ?: config('newdesk.supervisor.conf_dir');
        $path = rtrim($directory, '/').'/newdesk.conf';
        File::ensureDirectoryExists($directory);
        File::put($path, $config);
        $this->info("Supervisor config written to {$path}");

        if (! $this->option('no-reload')) {
            foreach ([['reread'], ['update'], ['restart', 'newdesk:*']] as $arguments) {
                $process = new Process(['supervisorctl', ...$arguments]);
                $process->run();
                $this->line(trim($process->getOutput().$process->getErrorOutput()));
                if (! $process->isSuccessful()) {
                    $this->error('supervisorctl failed: '.implode(' ', $arguments));

                    return self::FAILURE;
                }
            }
        }

        return self::SUCCESS;
    }

    private function render(): string
    {
        $php = PHP_BINARY;
        $artisan = base_path('artisan');
        $user = config('newdesk.supervisor.user');
        $logs = storage_path('logs');
        $blocks = [];
        $names = [];

        foreach (self::programs() as $name => $program) {
            $programName = "newdesk-{$name}";
            $names[] = $programName;
            $numprocs = $program['numprocs'] ?? 1;
            $blocks[] = implode("\n", array_filter([
                "[program:{$programName}]",
                $numprocs > 1 ? 'process_name=%(program_name)s_%(process_num)02d' : null,
                "command={$php} {$artisan} {$program['command']}",
                'autostart=true',
                'autorestart=true',
                "user={$user}",
                "numprocs={$numprocs}",
                'stopasgroup=true',
                'killasgroup=true',
                'stopwaitsecs='.($program['stopwaitsecs'] ?? 60),
                'redirect_stderr=true',
                "stdout_logfile={$logs}/supervisor-{$name}.log",
            ]));
        }

        $blocks[] = "[group:newdesk]\nprograms=".implode(',', $names);

        return "; Generated by `php artisan supervisor:sync` — do not edit by hand.\n\n".implode("\n\n", $blocks)."\n";
    }
}
